# Find the Greatest of Two Numbers in Python
# Using Loops
num1 , num2 = 10, 20
if num1>num2:
    print(num1,"is Greater")
else:
    print(num2,"is Greater")


#  Using Ternary Operator
num1, num2 = 20 , 60
print((num1 if num1>num2 else num2))



# Using inbuilt max() Function
num1, num2 = 20, 30
print(max(num1,num2))
